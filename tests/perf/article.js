// Синтетическая статья для замеров: по составу близка к научному тексту,
// ради которого приложение и написано, — заголовки, абзацы, цитаты, перечни,
// таблицы, код и горизонтальные линии. Однородный текст мерил бы не то:
// стоимость разметки строк зависит от того, внутри какого блока строка лежит.
export function buildArticle(targetLines) {
  const out = [];
  let section = 0;

  while (out.length < targetLines) {
    section += 1;
    out.push(`## Раздел ${section}. Постановка вопроса и обзор источников`);
    out.push("");
    for (let paragraph = 0; paragraph < 4; paragraph += 1) {
      out.push(
        `Исследование опирается на корпус источников ${section}.${paragraph}, где рассматривается связь между практикой чтения и институциональной рамкой издания; см. также сопоставительные данные ниже.`,
      );
      out.push(
        `Второе предложение абзаца ${paragraph} уточняет методологию: выборка формировалась по принципу теоретической насыщенности, а не репрезентативности генеральной совокупности.`,
      );
      out.push("");
    }
    out.push("> Цитата из источника, приводимая в подтверждение тезиса раздела.");
    out.push("> Продолжение цитаты во второй физической строке.");
    out.push("");
    out.push(`- Первый пункт перечня раздела ${section}`);
    out.push(`- Второй пункт перечня раздела ${section}`);
    out.push(`- Третий пункт перечня раздела ${section}`);
    out.push("");
    out.push("| Год | Показатель | Источник |");
    out.push("|:--|--:|:--|");
    out.push(`| 20${10 + (section % 15)} | ${100 + section} | Архив ${section} |`);
    out.push("");
    out.push("```");
    out.push(`код примера ${section}`);
    out.push("```");
    out.push("");
    out.push("---");
    out.push("");
  }

  return out.slice(0, targetLines).join("\n");
}
